#!/usr/bin/env node
/* NOSTALGIA — tools/perf/subset_fonts.mjs
 * Self-hosting experiment for the Google Fonts the game uses: collects every character that occurs
 * in index.html + style.css + src/*.js, subsets each downloaded Google woff2 file to those
 * characters (pyftsubset, layout features kept) and writes <out>/fonts.css with @font-face rules
 * (same unicode-range split as Google, font-display: swap) + the subset files.
 *
 *   node nostalgia/tools/perf/subset_fonts.mjs --in <dir from fonts.googleapis.com: fonts.css, list.json, *.woff2>
 *        --out <dir> [--python <python with fonttools + brotli>] [--src <repo nostalgia dir>]
 * Families kept: the ones style.css actually names (Baloo 2, Yatra One, VT323, Kalam). Noto Sans Telugu is
 * requested by index.html but no CSS rule uses it (Android ships Noto Sans Telugu as a system font).
 */
import { readFileSync, readdirSync, writeFileSync, mkdirSync, statSync, existsSync } from 'node:fs';
import { join, resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { execFileSync } from 'node:child_process';

const arg = (k, d) => { const i = process.argv.indexOf(k); return i > 0 ? process.argv[i + 1] : d; };
const SRC = resolve(arg('--src', join(dirname(fileURLToPath(import.meta.url)), '..', '..')));
const IN = resolve(arg('--in'));
const OUT = resolve(arg('--out'));
const PY = arg('--python', 'python3');
mkdirSync(OUT, { recursive: true });

let text = readFileSync(join(SRC, 'index.html'), 'utf8') + readFileSync(join(SRC, 'style.css'), 'utf8');
for (const f of readdirSync(join(SRC, 'src')).filter((f) => f.endsWith('.js') && !/assets3d_pack/.test(f))) text += readFileSync(join(SRC, 'src', f), 'utf8');
const used = [...new Set(text)].filter((c) => c.codePointAt(0) >= 32).map((c) => c.codePointAt(0).toString(16));
const css = readdirSync(IN).filter((f) => f.endsWith('.css')).map((f) => readFileSync(join(IN, f), 'utf8')).join('\n');
const list = JSON.parse(readFileSync(join(IN, 'list.json'), 'utf8'));
const usedCss = readFileSync(join(SRC, 'style.css'), 'utf8');
const KEEP = ['Baloo 2', 'Yatra One', 'VT323', 'Kalam'].filter((f) => usedCss.indexOf("'" + f + "'") >= 0);

// unicode-range per (family, weight, subset) from Google's css
const ranges = {};
for (const m of css.matchAll(/\/\* ([a-z-]+) \*\/\s*@font-face \{([^}]*)\}/g)) {
  const fam = (m[2].match(/font-family: '([^']+)'/) || [])[1];
  ranges[fam + '|' + m[1]] = (m[2].match(/unicode-range: ([^;]+);/) || [])[1];
}
const inRange = (cp, range) => range.split(',').some((r) => {
  const [a, b] = r.trim().replace('U+', '').split('-').map((x) => parseInt(x, 16));
  return b == null ? cp === a : cp >= a && cp <= b;
});

const rows = [];
let out = '/* self-hosted subset of Google Fonts (OFL) — generated by tools/perf/subset_fonts.mjs */\n';
const seen = new Set();
for (const f of list) {
  if (KEEP.indexOf(f.fam) < 0) continue;
  if (seen.has(f.url)) continue; // variable fonts: one file (one URL) serves every weight
  seen.add(f.url);
  const range = ranges[f.fam + '|' + f.subset];
  const cps = used.map((h) => parseInt(h, 16)).filter((cp) => inRange(cp, range));
  if (!cps.length) continue; // the browser would never download this subset
  const src = join(IN, f.fam.replace(/ /g, '_') + '_' + f.w + '_' + f.subset + '.woff2');
  const weights = list.filter((g) => g.url === f.url).map((g) => +g.w);
  const variable = weights.length > 1;
  const name = f.fam.replace(/ /g, '') + '-' + f.subset + (variable ? '' : '-' + f.w) + '.woff2';
  execFileSync(PY, ['-m', 'fontTools.subset', src, '--unicodes=' + cps.map((c) => c.toString(16)).join(','), '--layout-features=*', '--flavor=woff2', '--output-file=' + join(OUT, name)], { stdio: 'inherit' });
  const wDecl = variable ? Math.min(...weights) + ' ' + Math.max(...weights) : weights[0];
  out += "@font-face{font-family:'" + f.fam + "';font-style:normal;font-weight:" + wDecl + ';font-display:swap;src:url(' + name + ") format('woff2');unicode-range:" + range + '}\n';
  rows.push({ family: f.fam, weight: wDecl, subset: f.subset, chars: cps.length, google: statSync(src).size, subset_bytes: statSync(join(OUT, name)).size, file: name });
}
writeFileSync(join(OUT, 'fonts.css'), out);
writeFileSync(join(OUT, 'subset.json'), JSON.stringify(rows, null, 1));
for (const r of rows) console.log(r.family.padEnd(12) + String(r.weight).padEnd(9) + r.subset.padEnd(12) + String(r.chars).padStart(4) + ' chars  google ' + (r.google / 1024).toFixed(1).padStart(6) + ' KB -> subset ' + (r.subset_bytes / 1024).toFixed(1).padStart(6) + ' KB  ' + r.file);
