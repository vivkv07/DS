'use strict';
const fs = require('fs');
const path = require('path');
const ROOT = path.resolve(__dirname, '../..');
const G = require('./project.cjs');
const C = require('./check_projection.cjs');

const f1 = (v) => (+v).toFixed(1), f2 = (v) => (+v).toFixed(2), f0 = (v) => Math.round(v).toString();

function sizeTable(inp) {
  // the same checks for every world-size preset (same frame, other base scale)
  const rows = [];
  for (const [name, params] of Object.entries(G.PRESETS || {})) {
    const P = G.create(params);
    const r = C.runAll(P, inp, { fast: true, step: 80 });
    const m = (id) => { const e = inp.places[id]; return P.scaleAt(e.lat, e.lon); };
    rows.push({ name, base: 1 / params.baseUnitsPerMetre, r, ch: m('charminar'), ab: m('abids'), hm: m('home'), tb: m('tank_bund'), sc: m('secunderabad_clock_tower'), chosen: name === G.PRESET });
  }
  return rows;
}

function write(res, inp) {
  const P = G, par = P.PARAMS, g = res.grid, b = res.bearing, o = res.order, ov = res.overlap, sq = res.squeeze;
  const L = [];
  const push = (...s) => L.push(...s);
  const majors = ov.overlaps.filter((x) => !x.minor), minors = ov.overlaps.filter((x) => x.minor);
  const sizes = sizeTable(inp);
  const zoneScale = (id) => { const z = C.ZONES.find((q) => q.id === id); return P.scaleAt(z.lat, z.lon); };

  push('# Map v2 projection report (lat/lon -> world units)', '');
  push(`Generated by \`node tools/geo/check_projection.cjs --report\` on ${new Date().toISOString().slice(0, 10)}; the projection is`,
    '`tools/geo/project.cjs` (node, no dependencies; also loads as a classic script as `window.NOSTALGIA_GEO`).',
    'Re-run the command after changing the parameters; every number below is measured, not designed.', '');
  push('## Decision', '');
  push(`- **World size: ${par.world.w} x ${par.world.h} u** (preset \`${G.PRESET}\`), covering the A1 frame lon ${P.FRAME.lonW.toFixed(5)}-${P.FRAME.lonE.toFixed(5)} E,`,
    `  lat ${P.FRAME.latS.toFixed(5)}-${P.FRAME.latN.toFixed(5)} N (24.0 x 18.0 km) at one uniform base scale of **${f2(1 / par.baseUnitsPerMetre)} m per world unit**`,
    `  (${par.baseUnitsPerMetre.toFixed(4)} u/m), centred on ${par.centre.lat} N, ${par.centre.lon} E.`);
  push(`- **Warp:** \`${par.mode}\` mode, gain ${par.gain}: T(b) = b + gain / mean(rho) * grad(phi)(b), where lap(phi) = rho - mean(rho)`,
    '  with zero normal flux on the frame (a cosine-series Poisson solve on a ' + `${par.grid.nx} x ${par.grid.ny} grid). rho is the designed density`,
    '  (background 1 + heavy-tailed core kernels + a broad plateau + two weak sinks), so the local scale follows sqrt(rho / mean(rho)).');
  push(`- **Result:** local scale ${f2(g.mMin)}x-${f2(g.mMax)}x of the base (= ${f2(1 / (g.mMax * par.baseUnitsPerMetre))}-${f2(1 / (g.mMin * par.baseUnitsPerMetre))} m/u); no fold-overs`,
    `  (${g.negTriangles} of ${g.cells} grid triangles inverted); bearing change between neighbouring places: median ${f1(b.p50)} deg, p95 ${f1(b.p95)},`,
    `  p99 ${f1(b.p99)}, max ${f1(b.max)} deg (${b.over15} of ${b.pairs} pairs over 15 deg); order of places along roads: ${o.inversions} inversions in ${o.pairs} ordered pairs.`, '');

  push('## Method', '');
  push('1. **Base projection (uniform).** Equirectangular about the frame centre with WGS84 metres per degree at 17.3935 N',
    `   (${P.FRAME.mPerDegLat.toFixed(1)} m per degree of latitude, ${P.FRAME.mPerDegLon.toFixed(1)} m per degree of longitude): x = W/2 + dlon * m_lon * s,`,
    '   y = H/2 - dlat * m_lat * s with s the base u/m. Over the 18 km frame the east-west scale error of this choice is at most 0.05 %.',
    '2. **Warp (smooth, monotonic).** A linearised optimal-transport step: the warp is the gradient of the convex function',
    '   |b|^2 / 2 + gain * phi / mean(rho). Its Jacobian I + gain * Hess(phi) / mean(rho) is symmetric, so the warp has **no local rotation**',
    '   (north stays north everywhere), and it is a bijection wherever that Jacobian is positive definite (checked on the whole grid,',
    '   below). The cosine series gives phi zero normal derivative on the frame, so frame edges map onto world edges (corners stay put)',
    '   and points slide only along the edge. grad(phi) is evaluated from the series on the grid nodes (' + f1(par.world.w / par.grid.nx) + ' u apart) and interpolated bilinearly.',
    '   An alternative `flow` mode (Gastner-Seguy-More density-equalising flow) is kept in the code: it matches the designed scale',
    '   exactly but adds a curl (10 deg of local rotation at Charminar), so the gradient mode was chosen.',
    '3. **Density design.** Each kernel adds a * (1 + d^2 / s^2)^-p to the background 1. Heavy tails (p about 1) spread each core\'s',
    '   expansion over several km; a scale that falls off as r^-alpha has anisotropy 1 - alpha, and anisotropy q bends bearings by up to',
    '   90 - 2 atan(sqrt q) degrees (q = 0.6 -> 14.5 deg). The two sinks compress the empty ends of the dense band (south: Falaknuma,',
    '   Chandrayangutta, Barkas; north: the Cantonment) in both directions instead of only north-south.',
    '4. **Tuning.** `node tools/geo/tune_projection.cjs` runs a coordinate descent over every kernel\'s amplitude, radius, tail and position',
    '   and the gain. It minimises bearing error between neighbouring places plus shortfalls against per-core magnification targets.',
    '   The targets come from the footprint test (section "Room for the oversized landmarks").', '');
  push('Parameters (`PARAMS` in project.cjs):', '');
  push('| kernel | what it covers | lat | lon | a | s (m) | p |', '|---|---|---|---|---|---|---|');
  for (const c of par.cores.concat(par.plateau ? [Object.assign({ id: 'plateau', name: 'broad plateau over the historic city' }, par.plateau)] : [], par.sinks || [])) {
    push(`| ${c.id} | ${c.name || ''} | ${c.lat} | ${c.lon} | ${c.a} | ${c.s} | ${c.p} |`);
  }
  push('', `Background 1, gain ${par.gain}, Poisson grid ${par.grid.nx} x ${par.grid.ny}, mean(rho) = ${P.rhoBar.toFixed(3)}.`, '');

  push('## Scale per area', '');
  push('m = sqrt(det J) relative to the base; u/m = world units per real metre; aniso = smaller / larger principal stretch (1 = no',
    'shape change); "max brg" = worst bearing change of a very short segment at that point (any direction).', '');
  push('| area (place id) | world x, y | m | u/m | m/u | aniso | max brg (deg) |', '|---|---|---|---|---|---|---|');
  for (const a of res.areas) push(`| ${a.label} (\`${a.id}\`) | ${a.x}, ${a.y} | ${f2(a.m)} | ${f2(a.upm)} | ${f2(a.mpu)} | ${f2(a.aniso)} | ${f1(a.brg)} |`);
  push('');
  push(`Whole frame: m from ${f2(g.mMin)} to ${f2(g.mMax)} (${f2(g.mMin * par.baseUnitsPerMetre)}-${f2(g.mMax * par.baseUnitsPerMetre)} u/m). The empty outskirts (HITEC ${f2(zoneScale('outskirts_w').m)}x, Dilsukhnagar/LB Nagar`,
    `${f2(zoneScale('outskirts_se').m)}x) are compressed a little; the Old City gets the most room, then Abids/Koti and Himayatnagar, then Tank Bund and Secunderabad.`, '');

  push('## Checks', '');
  push('### 1. Bijection (no fold-overs)', '');
  push(`A ${g.nx} x ${g.ny} grid of ${g.step} u cells over the whole frame (${g.cells} triangles) was warped; **${g.negTriangles} triangles change orientation**.`,
    `Smallest Jacobian determinant ${f2(g.minDet)} (always > 0); largest local rotation ${f2(g.maxRot)} deg (numerical noise; the warp is a gradient).`,
    `Smallest anisotropy anywhere ${f2(g.minAniso)}; worst short-segment bearing change anywhere ${f1(g.maxBearing)} deg (the field is drawn in`,
    '`tests/out/geo/geo_warp_bearing.png`; it peaks in empty ground at the ends of the dense band).', '');
  push('### 2. Compass bearings between neighbouring places', '');
  push(`Each place's 6 nearest places within 1.5 km (and at least 20 m away) give **${b.pairs} pairs**. The world bearing of each pair is`,
    'compared with its real compass bearing:', '');
  push('| statistic | bearing change |', '|---|---|');
  push(`| median | ${f1(b.p50)} deg |`, `| mean | ${f2(b.mean)} deg |`, `| 95th percentile | ${f1(b.p95)} deg |`, `| 99th percentile | ${f1(b.p99)} deg |`, `| max | ${f1(b.max)} deg |`,
    `| pairs over 10 deg | ${b.over10} |`, `| pairs over 15 deg | ${b.over15} |`);
  push('', 'Worst pairs:', '');
  push('| pair | distance | bearing change |', '|---|---|---|');
  for (const w of b.worst.slice(0, 12)) push(`| \`${w.a}\` - \`${w.b}\` | ${w.d} m | ${f1(w.err)} deg |`);
  push('', `Not counted: ${b.layoutPairs.length} pairs between a fictional layout (colony, terraces, Patang Chacha's roof: placed by game-unit`,
    'offsets from an anchor, see "Using the projection") and a real point, and ' + `${b.offmapPairs.length} pairs with a point outside the frame (edge signposts).`, '');
  push('### 3. Order of places along every road', '');
  push(`${o.roads} road lines (roads.json plus the Himayatnagar grid lanes that are not duplicates of a named road) were densified every`,
    `20 m and projected; every place within 35 m of a road was located along it in reality and in the world. ${o.placesOnRoads} place-on-road`,
    `hits, ${o.pairs} ordered pairs (more than 3 m apart along the road): **${o.inversions} order inversions**.`, '');
  push('### 4. Landmark footprints (worlddata w x d at the projected centres)', '');
  push(`${ov.landmarks} landmark footprints were placed at their projected real centres. **${majors.length} overlaps between two sizeable,`,
    `non-low-confidence footprints**; ${minors.length} more involve a small prop (< 700 u^2) or a low-confidence (estimated) position.`, '');
  if (majors.length) {
    push('| footprints | overlap (u, smaller axis) | note |', '|---|---|---|');
    for (const x of majors) push(`| \`${x.a}\` x \`${x.b}\` | ${x.push} | ${x.confA}/${x.confB} confidence |`);
    push('');
  }
  push('Minor overlaps (the map builder nudges these by the overlap distance; positions are estimates or the props share a spot):', '');
  push(minors.map((x) => `\`${x.a}\` x \`${x.b}\` ${x.push} u`).join('; ') + '.', '');
  push('### 5. Room for roads (game widths)', '');
  push('Every road line was drawn at its game width (arterial 52, street 36, lane 22, bridge 40, bund 60 u). A stretch counts as',
    '"squeezed" where another road that does not meet it there (no junction within 2 x the two widths) comes closer than the two',
    `half-widths. Over the whole map ${f1(100 * sq.squeezed / sq.totalLen)} % of ${f0(sq.totalLen)} u of road is squeezed.`, '');
  push('| zone | road length (u) | squeezed | main squeezed pairs (min gap / needed, u) |', '|---|---|---|---|');
  for (const z of sq.zones) push(`| ${z.name} | ${f0(z.len)} | ${f1(100 * z.squeezed / Math.max(1, z.len))} % | ${z.top.slice(0, 3).map((t) => `${t.pair} (${t.minGap}/${t.need})`).join('; ')} |`);
  push('', 'Reading the table: a pair whose minimum gap is only 8-15 u (8-15 m real here) over a few hundred units is two lines for',
    'one street (parallel carriageways, or a game road and its OSM namesake, e.g. `mj_market_rd` / `mangalhat_rd`,',
    '`gowliguda_rd` / `jambagh_rd`); the builder keeps one of them. The only real lack of room is the Tank Bund pair (39 m apart, see',
    'below) and the Himayatnagar back lanes, where OSM lists every 3 m gully; draw the lanes that are 25 m or more apart.', '');

  push('## Room for the oversized landmarks (how the targets were set)', '');
  push('For each core: the smallest uniform local scale (u per real metre) at which the worlddata footprints (w x d) of two',
    'landmarks stop overlapping at their real positions, with no clearance / with a 12 u clearance, and what the projection',
    'gives there (the smaller u/m of the two landmarks). "Structural" pairs are two sizeable (>= 1500 u^2), non-low-confidence',
    'footprints; the "props" column is the tightest pair overall, usually two things that share one spot by design (a bakery inside',
    'a market, the clock tower in its chowk), which the builder nudges instead. "Gets" assumes one uniform scale; the warp grows',
    'towards the core, so the real test is check 4 above (e.g. LB Stadium and the State Museum keep a gap at their projected centres).', '');
  push('| core | binding structural pair | needs u/m (0 / 12 u gap) | gets u/m | tightest prop pair (needs u/m, 12 u gap) |', '|---|---|---|---|---|');
  for (const r of C.footprintNeeds(inp)) {
    const s0 = r.structural[0], a0 = r.all[0];
    const gets = (x) => Math.min(...[x.a, x.b].map((id) => P.scaleAt(inp.places[id].lat, inp.places[id].lon).upm));
    push(`| ${r.core} | ${s0 ? s0.pair : '-'} | ${s0 ? f2(s0.upm0) + ' / ' + f2(s0.upm12) : '-'} | ${s0 ? f2(gets(s0)) : '-'} | ${a0 ? a0.pair + ' (' + f2(a0.upm12) + ', gets ' + f2(gets(a0)) + ')' : '-'} |`);
  }
  push('');
  // plaza room: the largest square (half-size, u) centred on a landmark before it touches another big footprint
  const LM = {}; for (const l of inp.D.landmarks) LM[l.id] = l;
  const box = (id) => { const l = LM[id], w = P.placeWorld(inp.places[id]); return { x0: w[0] - l.w / 2, x1: w[0] + l.w / 2, y0: w[1] - l.d / 2, y1: w[1] + l.d / 2, cx: w[0], cy: w[1] }; };
  const room = (id, others) => {
    const c = box(id); let best = Infinity, who = '';
    for (const o of others) {
      if (!LM[o] || !inp.places[o]) continue;
      const b = box(o), dx = Math.max(b.x0 - c.cx, c.cx - b.x1, 0), dy = Math.max(b.y0 - c.cy, c.cy - b.y1, 0), d = Math.max(dx, dy);
      if (d < best) { best = d; who = o; }
    }
    return { half: best, who };
  };
  const big = ['mecca_masjid', 'chowmahalla_palace', 'madina_building', 'badshahi_ashurkhana', 'pista_house', 'murgi_chowk', 'pathergatti_arcade_w', 'gulzar_houz', 'charminar', 'hotel_nayaab', 'shadab_hotel'];
  const rc = room('charminar', big.filter((x) => x !== 'charminar')), rg = room('gulzar_houz', big.filter((x) => x !== 'gulzar_houz'));
  const gc = box('gulzar_houz'), cc = box('charminar');
  push(`Plazas: a square plaza centred on Charminar can reach a half-size of **${f0(rc.half)} u** before it touches \`${rc.who}\``,
    `(the old map's charminar_plaza had 162 u; the real pedestrian square is about 50 m = ${f0(50 * P.scaleAt(inp.places.charminar.lat, inp.places.charminar.lon).upm)} u here). Gulzar Houz sits`,
    `${f0(Math.hypot(gc.cx - cc.cx, gc.cy - cc.cy))} u north of Charminar; its square can reach ${f0(rg.half)} u (nearest: \`${rg.who}\`), the old one was 64 u.`,
    'The real Charminar circle road (radius about 34 m) projects to a ring of radius ' + f0(34 * P.scaleAt(inp.places.charminar.lat, inp.places.charminar.lon).upm) + ' u, inside the 64 u footprint\'s corners (45 u):',
    'the builder must redraw `charminar_circle` at a radius of 60 u or more and pull the four approach roads out to it.', '');
  push('The Himayatnagar colony is a fictional layout in game units, so it fits at any scale; the warp there only gives the real',
    'street grid around it room (the Himayatnagar lanes are 40-80 m apart, so 22 u lanes need about 1 u/m; it gets ' + f2(P.scaleAt(inp.places.home.lat, inp.places.home.lon).upm) + ').',
    'The Tank Bund and the Lower Tank Bund road run only 39 m apart (median, centre to centre); at game widths 60 + 52 u they would need',
    'about 1.6 u/m, which no smooth warp can give one 2.3 km strip without bending every bearing near it. The builder should draw the',
    'Lower Tank Bund as a 30-36 u street at the foot of the bund and let the bund keep its width.', '');

  push('## World size', '');
  push('The cores sit in one north-south band, Charminar to Secunderabad, 10 km long inside an 18 km frame. With bearings preserved, every',
    'north-south column of the frame must still add up to the world height, so whatever the band gains north-south, the strips',
    'beyond its ends (Falaknuma 4.8 km, the Cantonment 3.3 km) must lose. That column budget, not the area, limits the warp: at the',
    'same footprint needs a bigger world (a larger base scale) needs less relative magnification and bends bearings less. Same frame,',
    'same footprint targets in u/m, each preset tuned the same way:', '');
  push('| world (u) | base m/u | Charminar u/m | Abids u/m | home u/m | Tank Bund u/m | Clock Tower u/m | bearing p95 / p99 / max (deg) | over 15 deg |', '|---|---|---|---|---|---|---|---|---|');
  for (const s of sizes) push(`| ${s.chosen ? '**' + s.name + '** (chosen)' : s.name} | ${f2(s.base)} | ${f2(s.ch.upm)} | ${f2(s.ab.upm)} | ${f2(s.hm.upm)} | ${f2(s.tb.upm)} | ${f2(s.sc.upm)} | ${f1(s.r.bearing.p95)} / ${f1(s.r.bearing.p99)} / ${f1(s.r.bearing.max)} | ${s.r.bearing.over15} |`);
  push('', G.PRESET_NOTE || '', '');
  push('Engine budget (measured on this machine, headless Chromium): the current 8000 x 6000 world builds in 774 ms with 14,562',
    'structures and about 50 MB of JS heap. Build work and the collision grid (CELL 4 u) scale with area, so expect about 1.7 s /',
    '6.8 M cells at 12000 x 9000, about 2.7 s / 10.5 M cells at 15000 x 11250 (3.5x today) and about 3.1 s / 12 M cells at',
    '16000 x 12000, unless the builder generates fewer filler blocks in the compressed outskirts. Every engine module already reads',
    '`N.WORLD_W` / `N.WORLD_H`, so the size is one constant in core.js (owned by the engine team).', '');

  push('## Using the projection (for the worlddata builder)', '');
  push('```js',
    "const GEO = require('./tools/geo/project.cjs');   // or window.NOSTALGIA_GEO after a <script> tag",
    'GEO.project(17.36163, 78.47467)      // -> [x, y] world units (Charminar)',
    'GEO.unproject(x, y)                  // -> [lat, lon]',
    'GEO.projectLine(road.pts)            // [[lat, lon], ...] -> [[x, y], ...], densified every 40 m first',
    'GEO.placeWorld(places.json entry)    // anchor + offset_u layouts (colony, terraces, roofs) keep game units',
    'GEO.scaleAt(lat, lon)                // {m, upm, mpu, aniso, rot, bearingMaxErr}',
    'GEO.inFrame(lat, lon)                // false for edge signposts (they project outside 0..W x 0..H)',
    '```', '');
  push('- **Lines and rings:** always use `projectLine` / `projectRing` (they densify before projecting), so long straight OSM segments',
    '  follow the warp; ward and water rings stay closed.',
    '- **Fictional layouts:** entries with `anchor_latlon` + `offset_u` (Lakshmi Nagar colony, Ashok Nagar terraces, Patang Chacha\'s',
    '  roof) must be placed with `placeWorld()` = project(anchor) + offset_u, so roofs, planks and stairs keep their designed game-unit',
    '  spacing. Their own lat/lon are only the researcher\'s 2 m/u conversion.',
    '- **Outside the frame:** points beyond the frame (KPHB, JNTU, Bolarum, Rashtrapati Nilayam, Ramoji, Harina Vanasthali, University',
    '  of Hyderabad) project outside the world rectangle by their real distance; clamp them to edge signposts.',
    '- **Road widths by local scale:** game widths are 2.5-8x real widths. Where `scaleAt().upm` is below about 1 u/m, keep',
    '  arterials at 48-52 u but draw minor lanes only where they are at least (w1 + w2) / 2 apart; inside the Old City the',
    '  real lane network fits at 22 u lanes.',
    '- **Overlaps:** nudge the listed minor overlaps along the street they face; nothing needs to move more than the listed overlap.', '');
  push('## Previews (Playwright, `node tools/geo/preview.cjs`)', '');
  push('- `tests/out/geo/geo_world.png`: districts, GHMC wards (dashed), water, roads, rail and labelled must-have places in world space.',
    `- \`tests/out/geo/geo_vs_old.png\`: the same layers over the old 8000 x 6000 map scaled x${par.world.w / 8000}, with arrows from each must-have`,
    '  landmark\'s old position to its real projected position.',
    '- `tests/out/geo/geo_warp.png` / `geo_warp_bearing.png`: the warped 0.005 deg graticule over the local scale / bearing-change field.',
    '- `tests/out/geo/geo_zoom_old_city.png`, `geo_zoom_abids_koti.png`, `geo_zoom_himayatnagar.png`, `geo_zoom_secunderabad.png`,',
    '  `geo_zoom_tank_bund.png`: roads at game widths and landmark footprints at about 1 px per unit.', '');
  push('## Data and attribution', '');
  push('- `design/geo/places.json` (written by `tools/geo/merge_places.cjs`): the two researchers\' files merged, ' +
    `${Object.keys(inp.places).length} ids (high ${countConf(inp.places, 'high')}, medium ${countConf(inp.places, 'medium')}, low ${countConf(inp.places, 'low')}); every entry keeps`,
    '  its confidence, source, ward and the losing candidate (`alt`) where the two disagreed. Merge rules used: ' + mergeStats() + '.',
    '- Map reference: DataMeet Municipal Spatial Data (CC BY 4.0) and (c) OpenStreetMap contributors (ODbL). Roads, water and rail:',
    '  (c) OpenStreetMap contributors (ODbL) via Overture Maps Foundation. Stations: datameet/railways (CC0). Elevation: Terrain Tiles',
    '  on AWS Open Data (SRTM, public domain).', '');
  push('## Regenerating', '');
  push('```sh',
    'node tools/geo/merge_places.cjs                              # design/geo/places.json from the two researcher files',
    'node tools/geo/tune_projection.cjs --preset 15000x11250       # optional: re-tune (prints new parameters for PRESETS)',
    'node tools/geo/check_projection.cjs --report                  # all checks + this report',
    'node tools/geo/preview.cjs                                    # tests/out/geo/*.png (Playwright)',
    '```', '');
  fs.writeFileSync(path.join(ROOT, 'design/geo/projection_report.md'), L.join('\n'));
  console.log('wrote design/geo/projection_report.md');
}
function mergeStats() {
  try {
    const m = require(path.join(ROOT, 'design/geo/places.json')).meta.counts.merge;
    return `only north-west file ${m.only_nw}, only south-east file ${m.only_se}, in both ${m.both} (` +
      Object.entries(m.rules).filter(([k]) => !/^only_/.test(k)).map(([k, v]) => `${k.replace(/_/g, ' ')} ${v}`).join(', ') + `), aliases re-synced ${m.alias_synced}`;
  } catch (e) { return 'see places.json meta'; }
}
function countConf(P, c) { return Object.values(P).filter((e) => e.confidence === c).length; }

module.exports = { write };
