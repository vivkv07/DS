#!/usr/bin/env node
/* NOSTALGIA — tools/vendor_fonts.mjs: self-host the Google Fonts the game uses (SIL Open Font License) in vendor/fonts/
 * (performance audit PERF-18, round 2: the Google css2 stylesheet in index.html was render-blocking and a third origin).
 *
 *   node nostalgia/tools/vendor_fonts.mjs [--python <python with fonttools + brotli>]
 *
 * 1. fetches Google's css2 for the families style.css / menus.js / story2.js name (a desktop Chrome user agent: woff2
 *    split by unicode-range subsets), and each family's OFL.txt from github.com/google/fonts;
 * 2. subsets every woff2 whose unicode-range the game can use to: the characters in index.html, style.css and src/*.js
 *    (not the model pack) + all of printable ASCII, Latin-1, general punctuation and ₹ (a typed nickname or a save made
 *    by a newer build still renders), keeping every OpenType layout feature (Telugu shaping);
 * 3. writes vendor/fonts/<Family>-<subset>[-<weight>].woff2, vendor/fonts/fonts.css (@font-face, font-display: swap,
 *    Google's unicode-range per subset) and vendor/fonts/OFL-<Family>.txt + vendor/fonts/README.md.
 * index.html links vendor/fonts/fonts.css; tools/build.mjs inlines it (font URLs rebased to the page) and
 * tools/deploy_site.sh copies vendor/fonts/ to the site. Re-run when new text adds characters (a missing glyph only
 * falls back to the next font in the CSS stack).
 */
import { readFileSync, writeFileSync, mkdirSync, readdirSync, statSync, rmSync, existsSync } from 'node:fs';
import { join, resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { execFileSync } from 'node:child_process';

const arg = (k, d) => { const i = process.argv.indexOf(k); return i > 0 ? process.argv[i + 1] : d; };
const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = join(ROOT, 'vendor', 'fonts');
const PY = arg('--python', 'python3');
const UA = 'Mozilla/5.0 (X11; Linux x86_64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/139.0.0.0 Safari/537.36';
const FAMILIES = [
  // [css2 family spec, google/fonts repo dir]
  ['Baloo+2:wght@400;600;800', 'ofl/baloo2'],
  ['Yatra+One', 'ofl/yatraone'],
  ['VT323', 'ofl/vt323'],
  ['Noto+Sans+Telugu:wght@400;700', 'ofl/notosanstelugu'],
  ['Kalam:wght@400;700', 'ofl/kalam'],
];

const get = async (url, bin) => {
  const r = await fetch(url, { headers: { 'User-Agent': UA } });
  if (!r.ok) throw new Error(url + ': HTTP ' + r.status);
  return bin ? Buffer.from(await r.arrayBuffer()) : r.text();
};

// the characters the game can show
let text = readFileSync(join(ROOT, 'index.html'), 'utf8') + readFileSync(join(ROOT, 'style.css'), 'utf8');
for (const f of readdirSync(join(ROOT, 'src')).filter((f) => f.endsWith('.js') && !/assets3d_pack/.test(f))) text += readFileSync(join(ROOT, 'src', f), 'utf8');
const used = new Set();
for (const ch of text) { const cp = ch.codePointAt(0); if (cp >= 32) used.add(cp); }
for (let cp = 0x20; cp <= 0x7e; cp++) used.add(cp);
for (let cp = 0xa0; cp <= 0xff; cp++) used.add(cp);
for (let cp = 0x2010; cp <= 0x2027; cp++) used.add(cp);
for (const cp of [0x2030, 0x2032, 0x2033, 0x2039, 0x203a, 0x20b9, 0x2122]) used.add(cp);

const inRange = (cp, range) => range.split(',').some((r) => {
  const [a, b] = r.trim().replace(/U\+/g, '').split('-').map((x) => parseInt(x, 16));
  return b == null ? cp === a : cp >= a && cp <= b;
});

const tmp = join(OUT, '.tmp');
rmSync(OUT, { recursive: true, force: true });
mkdirSync(tmp, { recursive: true });
let css = '/* NOSTALGIA — self-hosted subsets of Google Fonts (SIL Open Font License 1.1, see OFL-*.txt).\n' +
  ' * Generated by tools/vendor_fonts.mjs: do not edit. font-display: swap (text shows at once in a fallback font). */\n';
const rows = [];
for (const [spec, repo] of FAMILIES) {
  const sheet = await get('https://fonts.googleapis.com/css2?family=' + spec + '&display=swap');
  const faces = [...sheet.matchAll(/\/\* ([a-z0-9-]+) \*\/\s*@font-face \{([^}]*)\}/g)].map((m) => ({
    subset: m[1], fam: (m[2].match(/font-family: '([^']+)'/) || [])[1], weight: (m[2].match(/font-weight: (\d+)/) || [])[1],
    url: (m[2].match(/url\(([^)]+)\)/) || [])[1], range: (m[2].match(/unicode-range: ([^;]+);/) || [])[1],
  }));
  const fam = faces[0].fam;
  writeFileSync(join(OUT, 'OFL-' + fam.replace(/ /g, '') + '.txt'), await get('https://raw.githubusercontent.com/google/fonts/main/' + repo + '/OFL.txt'));
  const done = new Map(); // url -> file (a variable font serves several weights from one file)
  for (const f of faces) {
    const cps = [...used].filter((cp) => inRange(cp, f.range));
    if (!cps.length) continue; // the browser would never download this subset
    const weights = faces.filter((g) => g.url === f.url).map((g) => +g.weight);
    if (done.has(f.url)) continue;
    const variable = weights.length > 1;
    const name = fam.replace(/ /g, '') + '-' + f.subset + (variable ? '' : '-' + f.weight) + '.woff2';
    const src = join(tmp, name + '.src');
    writeFileSync(src, await get(f.url, true));
    execFileSync(PY, ['-m', 'fontTools.subset', src, '--unicodes=' + cps.map((c) => c.toString(16)).join(','), '--layout-features=*', '--flavor=woff2', '--output-file=' + join(OUT, name)], { stdio: 'inherit' });
    done.set(f.url, name);
    const wDecl = variable ? Math.min(...weights) + ' ' + Math.max(...weights) : weights[0];
    css += "@font-face{font-family:'" + fam + "';font-style:normal;font-weight:" + wDecl + ';font-display:swap;src:url(' + name + ") format('woff2');unicode-range:" + f.range + '}\n';
    rows.push([fam, String(wDecl), f.subset, cps.length, statSync(src).size, statSync(join(OUT, name)).size, name]);
  }
}
writeFileSync(join(OUT, 'fonts.css'), css);
rmSync(tmp, { recursive: true, force: true });
let total = 0, google = 0;
let md = '# vendor/fonts\n\nSelf-hosted subsets of the Google Fonts the game uses, made by `tools/vendor_fonts.mjs` (do not edit by hand).\n' +
  'Each font is licensed under the SIL Open Font License 1.1 (the `OFL-*.txt` next to it).\n\n| family | weight | subset | chars | Google woff2 | subset |\n|---|---|---|---|---|---|\n';
for (const r of rows) { total += r[5]; google += r[4]; md += '| ' + r[0] + ' | ' + r[1] + ' | ' + r[2] + ' | ' + r[3] + ' | ' + (r[4] / 1024).toFixed(1) + ' KB | ' + (r[5] / 1024).toFixed(1) + ' KB |\n'; }
md += '\nTotal: ' + (total / 1024).toFixed(1) + ' KB (Google files for the same subsets: ' + (google / 1024).toFixed(1) + ' KB). The browser downloads only the\nsubsets whose unicode-range a page actually shows.\n';
writeFileSync(join(OUT, 'README.md'), md);
for (const r of rows) console.log(r[0].padEnd(17) + r[1].padEnd(9) + r[2].padEnd(13) + String(r[3]).padStart(4) + ' chars  google ' + (r[4] / 1024).toFixed(1).padStart(6) + ' KB -> ' + (r[5] / 1024).toFixed(1).padStart(6) + ' KB  ' + r[6]);
console.log('vendor/fonts: ' + rows.length + ' files, ' + (total / 1024).toFixed(1) + ' KB (Google: ' + (google / 1024).toFixed(1) + ' KB)');
if (!existsSync(join(OUT, 'fonts.css'))) process.exit(1);
